#!/usr/bin/env node
// Regenerates static files whose content depends on BASE_PATH.
// Keeps base-path.json as the single source of truth — running this script
// rewrites src/robots.txt and src/opensearch.xml from the values in JSON.

const fs = require('fs');
const path = require('path');
const {basePath, canonicalOrigin} = require('../base-path.json');

const canonicalUrl = canonicalOrigin + basePath;
const repoRoot = path.resolve(__dirname, '..');

const robotsTxt = `# Auto-generated by tools/apply-base-path.js — edit base-path.json instead.
User-agent: *
Allow: /

Sitemap: ${canonicalUrl}sitemap-index.xml
`;

const openSearchXml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Auto-generated by tools/apply-base-path.js - edit base-path.json instead. -->
<OpenSearchDescription xmlns="http://a9.com/-/spec/opensearch/1.1/">
  <ShortName>Rylo Translate</ShortName>
  <Description>Translate between spoken and signed languages</Description>
  <InputEncoding>UTF-8</InputEncoding>
  <Url type="text/html" template="${canonicalUrl}?text={searchTerms}" />
</OpenSearchDescription>
`;

const basePathScss = `// Auto-generated by tools/apply-base-path.js - edit base-path.json instead.
$base-path: '${basePath}';
`;

const indexHtmlPath = path.join(repoRoot, 'src/index.html');
const indexHtml = fs.readFileSync(indexHtmlPath, 'utf8');
const canonicalRe = /<link rel="canonical" href="[^"]*" \/>/;
const canonicalTag = `<link rel="canonical" href="${canonicalUrl}" />`;
if (!canonicalRe.test(indexHtml)) {
  throw new Error('src/index.html is missing a <link rel="canonical"> tag for apply-base-path to update');
}
const updatedIndexHtml = indexHtml.replace(canonicalRe, canonicalTag);

fs.writeFileSync(path.join(repoRoot, 'src/robots.txt'), robotsTxt);
fs.writeFileSync(path.join(repoRoot, 'src/opensearch.xml'), openSearchXml);
fs.writeFileSync(path.join(repoRoot, 'src/theme/_base-path.scss'), basePathScss);
fs.writeFileSync(indexHtmlPath, updatedIndexHtml);
console.log(`Applied basePath=${basePath} to robots.txt, opensearch.xml, _base-path.scss, and index.html canonical`);
